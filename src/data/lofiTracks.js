class LofiAudioEngine {
  constructor() {
    this.audio = typeof Audio !== 'undefined' ? new Audio() : null;
    this.currentTrackUrl = null;
    this.volume = 0.6;
    this.onTrackEndCallback = null;

    if (this.audio) {
      this.audio.volume = this.volume;
      this.audio.preload = 'auto';
      this.audio.addEventListener('ended', () => {
        if (this.onTrackEndCallback) {
          this.onTrackEndCallback();
        }
      });
      this.audio.addEventListener('error', (e) => {
        console.warn('Audio streaming error:', e);
      });
    }
  }

  setTrackEndCallback(callback) {
    this.onTrackEndCallback = callback;
  }

  playTrack(track) {
    if (!this.audio) return;
    if (this.currentTrackUrl !== track.url) {
      this.currentTrackUrl = track.url;
      this.audio.src = track.url;
    }
    this.audio.play().catch((err) => {
      console.log('Playback started or waiting for user interaction:', err);
    });
  }

  play() {
    if (this.audio && this.audio.src) {
      this.audio.play().catch(() => {});
    }
  }

  pause() {
    if (this.audio) {
      this.audio.pause();
    }
  }

  setVolume(vol) {
    this.volume = Math.max(0, Math.min(1, vol));
    if (this.audio) {
      this.audio.volume = this.volume;
    }
  }
}

export const ambientAudio = new LofiAudioEngine();
