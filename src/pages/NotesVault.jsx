import React, { useState } from 'react';
import { useNavigate } from 'react-router-dom';
import { useAuth } from '../context/AuthContext';
import { useAI } from '../context/AIContext';
import GoogleDriveExplorer from '../features/drive/GoogleDriveExplorer';
import GoogleDriveViewer from '../features/drive/GoogleDriveViewer';
import AIKeyPointsModal from '../features/revision/AIKeyPointsModal';
import AIProficiencyQuizModal from '../features/revision/AIProficiencyQuizModal';
import ForgeDeckModal from '../features/drive/ForgeDeckModal';
import { fetchDriveFileFullContent, fetchDriveFileTextContent } from '../services/googleDriveService';
import { 
  CheckCircle2, HardDrive, Sparkles, ExternalLink, Key
} from 'lucide-react';

export default function NotesVault() {
  const navigate = useNavigate();
  const { user, driveToken, requestDriveAccess, disconnectDrive, setShowLogin } = useAuth();
  const { generateKeyPoints, generateQuiz, hasCustomKey, setShowAISettingsModal, isGenerating } = useAI();

  const [selectedFile, setSelectedFile] = useState(null);
  const [showKeyPointsModal, setShowKeyPointsModal] = useState(false);
  const [showQuizModal, setShowQuizModal] = useState(false);
  const [showForgeModal, setShowForgeModal] = useState(false);
  const [targetFileForForge, setTargetFileForForge] = useState(null);
  const [activeTargetFile, setActiveTargetFile] = useState(null);
  const [keyPoints, setKeyPoints] = useState([]);
  const [customQuizQuestions, setCustomQuizQuestions] = useState(null);
  const [quizSubject, setQuizSubject] = useState('Google Drive Note');

  // In-app Toast notification state
  const [toast, setToast] = useState(null);
  const [explorerRefreshKey, setExplorerRefreshKey] = useState(0);

  const showToast = (message, type = 'success') => {
    setToast({ message, type });
    setTimeout(() => {
      setToast(null);
    }, 3200);
  };

  // Google Drive AI Handlers
  const handleGenerateKeyPoints = async (file) => {
    setActiveTargetFile(file);
    showToast(`Reading and analyzing "${file.name}" with Gemini AI...`, 'info');
    
    try {
      const { text, fileData } = await fetchDriveFileFullContent(driveToken, file);
      const generated = await generateKeyPoints(file.name, text, fileData);
      if (generated && generated.length > 0) {
        setKeyPoints(generated);
        setShowKeyPointsModal(true);
        showToast('Key takeaways generated by Gemini AI!', 'success');
      } else {
        throw new Error('Gemini returned an empty response. Please verify the document text content.');
      }
    } catch (err) {
      console.error('AI Key Points generation failed:', err);
      setKeyPoints([]);
      setShowKeyPointsModal(false);
      showToast(err.message || 'AI generation failed.', 'error');
      if (err.code === 'NO_API_KEY' || err.code === 'QUOTA_EXCEEDED' || err.code === 'INVALID_KEY') {
        setShowAISettingsModal(true);
      }
    }
  };

  const handleGenerateQuiz = async (file) => {
    setActiveTargetFile(file);
    showToast(`Synthesizing practice quiz for "${file.name}"...`, 'info');
    
    try {
      const { text, fileData } = await fetchDriveFileFullContent(driveToken, file);
      const generatedQuestions = await generateQuiz(file.name, text, 5, fileData);
      if (generatedQuestions && generatedQuestions.length > 0) {
        setCustomQuizQuestions(generatedQuestions);
        setQuizSubject(file.name.replace(/\.[^/.]+$/, ''));
        setShowQuizModal(true);
        showToast('AI Quiz ready! Test your recall.', 'success');
      } else {
        throw new Error('Gemini could not generate quiz questions from this document.');
      }
    } catch (err) {
      console.error('AI Quiz generation error:', err);
      setCustomQuizQuestions(null);
      setShowQuizModal(false);
      showToast(err.message || 'Quiz generation failed.', 'error');
      if (err.code === 'NO_API_KEY' || err.code === 'QUOTA_EXCEEDED' || err.code === 'INVALID_KEY') {
        setShowAISettingsModal(true);
      }
    }
  };

  return (
    <div className="max-w-7xl mx-auto px-4 sm:px-6 py-6 space-y-6 animate-fade-in relative">
      
      {/* Toast Notification Pill */}
      {toast && (
        <div className="fixed bottom-6 right-6 z-50 flex items-center gap-2.5 px-4 py-3 rounded-2xl bg-[rgb(var(--color-card))] border border-[#9e3c26]/40 shadow-2xl text-xs font-semibold text-[rgb(var(--color-text))] animate-in fade-in slide-in-from-bottom-4 duration-200">
          <span className="w-5 h-5 rounded-full bg-[#9e3c26]/10 text-[#9e3c26] dark:text-[#ffb4a3] flex items-center justify-center shrink-0">
            <CheckCircle2 size={13} />
          </span>
          <span>{toast.message}</span>
        </div>
      )}

      {/* Header & Cloud Actions */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 pb-3 border-b border-[rgb(var(--color-border))]">
        <div className="space-y-1">
          <div className="flex items-center gap-3 flex-wrap">
            <h1 className="text-2xl font-bold tracking-tight text-[rgb(var(--color-text))]">
              Notes Vault
            </h1>
            <span className="inline-flex items-center gap-1.5 px-2.5 py-1 rounded-full bg-[#9e3c26]/10 text-[#9e3c26] dark:text-[#ffb4a3] text-[11px] font-semibold border border-[#9e3c26]/20">
              <HardDrive size={12} />
              <span>Google Drive Cloud</span>
            </span>
          </div>
          <p className="text-xs text-[rgb(var(--color-muted))]">
            Browse, search, and preview your Google Drive notes, lecture slides, and dossiers. Launch AI summaries and quiz duels directly inside Rivis.
          </p>
        </div>

        <div className="flex items-center gap-2 flex-wrap">
          <button
            onClick={() => setShowAISettingsModal(true)}
            className={`px-3 py-1.5 rounded-xl border text-xs font-semibold flex items-center gap-1.5 transition-colors cursor-pointer ${
              hasCustomKey
                ? 'bg-emerald-500/10 border-emerald-500/30 text-emerald-700 dark:text-emerald-300'
                : 'bg-[rgb(var(--color-container-low))] hover:bg-[rgb(var(--color-container))] text-[rgb(var(--color-text))] border-[rgb(var(--color-border))]'
            }`}
            title="Configure Gemini AI Key & Quota"
          >
            <Sparkles size={13} className={hasCustomKey ? 'text-emerald-500' : 'text-[#9e3c26] dark:text-[#ffb4a3]'} />
            <span>{hasCustomKey ? 'AI: Personal Quota' : 'AI Quota'}</span>
          </button>

          {!driveToken ? (
            <button
              onClick={() => {
                if (!user) {
                  setShowLogin(true);
                  return;
                }
                requestDriveAccess().then(res => {
                  if (res?.success) {
                    showToast('Google Drive connected successfully!', 'success');
                    setExplorerRefreshKey(k => k + 1);
                  } else if (res?.error) {
                    showToast(res.error, 'error');
                  }
                });
              }}
              className="px-3.5 py-1.5 rounded-xl bg-[#9e3c26] hover:bg-[#be543c] dark:bg-[#e26f54] text-white font-semibold text-xs flex items-center gap-1.5 shadow-sm shadow-[#9e3c26]/25 cursor-pointer transition-all"
            >
              <Sparkles size={14} />
              <span>Connect Google Drive</span>
            </button>
          ) : (
            <div className="flex items-center gap-2">
              <button
                onClick={() => {
                  requestDriveAccess().then(res => {
                    if (res?.success) {
                      showToast('Google Drive re-authenticated!', 'success');
                      setExplorerRefreshKey(k => k + 1);
                    } else if (res?.error) {
                      showToast(res.error, 'error');
                    }
                  });
                }}
                className="px-3 py-1.5 rounded-xl bg-[rgb(var(--color-container-low))] hover:bg-[rgb(var(--color-container))] text-[rgb(var(--color-text))] font-semibold text-xs border border-[rgb(var(--color-border))] flex items-center gap-1.5 transition-colors cursor-pointer"
                title="Re-authenticate or grant additional Google Drive permissions"
              >
                <Sparkles size={13} className="text-[#9e3c26] dark:text-[#ffb4a3]" />
                <span>Re-link Drive</span>
              </button>

              <button
                onClick={() => {
                  disconnectDrive();
                  showToast('Google Drive disconnected.');
                  setSelectedFile(null);
                }}
                className="px-3 py-1.5 rounded-lg bg-[rgb(var(--color-container-low))] hover:bg-red-500/10 hover:text-red-600 text-[rgb(var(--color-muted))] text-xs font-medium border border-[rgb(var(--color-border))] cursor-pointer transition-colors"
                title="Disconnect Google Drive"
              >
                Disconnect
              </button>

              <a
                href="https://drive.google.com"
                target="_blank"
                rel="noopener noreferrer"
                className="px-3 py-1.5 rounded-xl bg-[rgb(var(--color-container-low))] hover:bg-[rgb(var(--color-container))] text-[rgb(var(--color-text))] font-medium text-xs border border-[rgb(var(--color-border))] flex items-center gap-1.5 transition-colors cursor-pointer"
                title="Open Google Drive in new tab"
              >
                <ExternalLink size={13} className="text-[#9e3c26] dark:text-[#ffb4a3]" />
                <span>drive.google.com</span>
              </a>
            </div>
          )}
        </div>
      </div>

      {/* Google Drive Notes Vault: Explorer & Document Viewer */}
      <div className="grid grid-cols-1 lg:grid-cols-12 gap-6 items-start">
        {/* Left Column: Google Drive Explorer */}
        <div className="lg:col-span-5">
          <GoogleDriveExplorer
            token={driveToken}
            selectedFile={selectedFile}
            onSelectFile={(file) => setSelectedFile(file)}
            onRequestAuth={() => {
              if (!user) {
                setShowLogin(true);
                return;
              }
              requestDriveAccess().then(res => {
                if (res?.success) {
                  showToast('Google Drive connected successfully!', 'success');
                  setExplorerRefreshKey(k => k + 1);
                } else if (res?.error) {
                  showToast(res.error, 'error');
                }
              });
            }}
            onToast={showToast}
            externalRefreshKey={explorerRefreshKey}
          />
        </div>

        {/* Right Column: Google Drive Viewer */}
        <div className="lg:col-span-7">
          <GoogleDriveViewer
            token={driveToken}
            file={selectedFile}
            onGenerateKeyPoints={handleGenerateKeyPoints}
            onGenerateQuiz={handleGenerateQuiz}
            onTriggerForge={(file) => {
              setTargetFileForForge(file);
              setShowForgeModal(true);
            }}
            onToast={showToast}
          />
        </div>
      </div>

      {/* Summary & Mindmap Generation Modal */}
      {showForgeModal && targetFileForForge && (
        <ForgeDeckModal
          isOpen={showForgeModal}
          onClose={() => setShowForgeModal(false)}
          file={targetFileForForge}
          driveToken={driveToken}
          onDeckForged={(fileId, deck, uploadedFile) => {
            const baseName = targetFileForForge.name.replace(/^Summary\s*-\s*/i, '').replace(/\.[^/.]+$/, '');
            setExplorerRefreshKey(k => k + 1);
            showToast(`🎉 Summary & Mindmap updated for "${baseName}"!`, 'success');
            if (uploadedFile) {
              setSelectedFile(uploadedFile);
            }
          }}
          onViewSummaryNow={(file) => {
            setSelectedFile(file);
          }}
        />
      )}

      {/* AI Key Points Modal */}
      {showKeyPointsModal && activeTargetFile && (
        <AIKeyPointsModal
          isOpen={showKeyPointsModal}
          onClose={() => setShowKeyPointsModal(false)}
          topic={activeTargetFile.name.replace(/\.[^/.]+$/, '')}
          subject="Google Drive Note"
          keyPoints={keyPoints}
          onStartQuiz={() => {
            setShowKeyPointsModal(false);
            setShowQuizModal(true);
          }}
        />
      )}

      {/* AI Proficiency Quiz Modal */}
      {showQuizModal && activeTargetFile && (
        <AIProficiencyQuizModal
          isOpen={showQuizModal}
          onClose={() => setShowQuizModal(false)}
          topic={activeTargetFile.name.replace(/\.[^/.]+$/, '')}
          subject={quizSubject}
          customQuestions={customQuizQuestions}
          onViewKeyPoints={() => {
            setShowQuizModal(false);
            setShowKeyPointsModal(true);
          }}
        />
      )}

    </div>
  );
}
